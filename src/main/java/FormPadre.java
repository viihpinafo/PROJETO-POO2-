    private void BtCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtCadastrarActionPerformed
        BDFiel bd = BDFiel.geraBDFiel();
        Padre p = new Padre();

    try{
           p.setNome(TextNome.getText());
           p.setIdade(Integer.parseInt(TextIdade.getText()));
    }
    catch(NomePequenoException npe){
           javax.swing.JOptionPane.showMessageDialog(null, "Nome muito pequeno!");
    return;
    }
    catch(IdadeInvalidaException iie){
           javax.swing.JOptionPane.showMessageDialog(null, "Idade inválida!");
    return;
    }

        p.setCpf(Integer.parseInt(TextCpf.getText()));
        p.setCidade(TextCidade.getText());
        p.setSetorParoquia(TextSetor.getText());
        p.getParoquia().setNome(TextParoquia.getText()); //Reflexividade

        bd.insFiel(p);

            javax.swing.JOptionPane.showMessageDialog(null, "Padre cadastrado!");
            
            TextNome.setText("");
            TextCpf.setText("");
            TextIdade.setText("");
            TextCidade.setText("");
            TextSetor.setText("");
            TextParoquia.setText("");
    }//GEN-LAST:event_BtCadastrarActionPerformed

