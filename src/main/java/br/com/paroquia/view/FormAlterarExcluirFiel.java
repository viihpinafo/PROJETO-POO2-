    private void BtConsulActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtConsulActionPerformed
        try {
            Fiel f = new FielController().consultar(TextConCpf.getText());
            if (f == null) {
                ResulTextNo.setText("");
                javax.swing.JOptionPane.showMessageDialog(this,"Fiel não encontrado.");
            } else ResulTextNo.setText(f.getNome());
        } catch (Exception ex) { ErrosTela.mostrar(this,ex); }
    }//GEN-LAST:event_BtConsulActionPerformed

    private void BtExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtExcluirActionPerformed
        try {
            FielController controller = new FielController();
            if (controller.consultar(TextConCpf.getText()) == null) {
                javax.swing.JOptionPane.showMessageDialog(this,"Fiel não encontrado."); return;
            }
            int opcao=javax.swing.JOptionPane.showConfirmDialog(this,"Confirma a exclusão do fiel?", "Excluir",javax.swing.JOptionPane.YES_NO_OPTION);
            if (opcao==javax.swing.JOptionPane.YES_OPTION && controller.excluir(TextConCpf.getText())) {
                javax.swing.JOptionPane.showMessageDialog(this,"Fiel excluído.");
                TextConCpf.setText("");ResulTextNo.setText("");
            }
        } catch (Exception ex) { ErrosTela.mostrar(this,ex); }
    }//GEN-LAST:event_BtExcluirActionPerformed

    private void BtAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtAlterarActionPerformed
        try {
            boolean alterado = new FielController().alterarNome(TextConCpf.getText(),ResulTextNo.getText());
            javax.swing.JOptionPane.showMessageDialog(this,alterado?"Nome atualizado!":"Fiel não encontrado.");
        } catch (Exception ex) { ErrosTela.mostrar(this,ex); }
    }//GEN-LAST:event_BtAlterarActionPerformed

