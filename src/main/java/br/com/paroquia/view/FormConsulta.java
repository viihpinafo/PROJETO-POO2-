    private void BtConsulActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtConsulActionPerformed
        try {
            Fiel f = new FielController().consultar(TextConCpf.getText());
            ResulTextNo.setText(""); ResulTextId.setText("");
            ResulTextCar.setText(""); ResulTextParo.setText("");
            if (f == null) {
                javax.swing.JOptionPane.showMessageDialog(this,"Fiel não encontrado com esse CPF.");
                return;
            }
            ResulTextNo.setText(f.getNome());
            ResulTextId.setText(String.valueOf(f.getIdade()));
            ResulTextCar.setText(FielController.cargo(f));
            ResulTextParo.setText(f.getParoquia().getNome());
        } catch (Exception ex) { ErrosTela.mostrar(this,ex); }
    }//GEN-LAST:event_BtConsulActionPerformed

