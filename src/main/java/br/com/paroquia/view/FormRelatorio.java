    public void atualizarTabela(){
        javax.swing.table.DefaultTableModel modelo=(javax.swing.table.DefaultTableModel)TabFieis.getModel();
        modelo.setRowCount(0);
        try {
            for(Fiel f : new FielController().listar()) {
                modelo.addRow(new Object[]{f.getNome(),f.getCpf(),f.getIdade(),
                    FielController.cargo(f),f.getParoquia().getNome()});
            }
        } catch(Exception e) { ErrosTela.mostrar(this,e); }
    }

