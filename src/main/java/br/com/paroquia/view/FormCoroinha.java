    private void BtCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtCadastrarActionPerformed
        try {
            Coroinha c = new Coroinha();
            c.setNome(TextNome.getText());
            c.setIdade(Conversores.inteiro(TextIdade.getText(), "idade"));
            c.setCpf(Conversores.cpf(TextCpf.getText()));
            c.setEscala(TextEscala.getText());
            c.setTempoPastoral(TextTemPast.getText());
            c.getParoquia().setNome(TextParoquia.getText());
            new FielController().cadastrar(c);
            javax.swing.JOptionPane.showMessageDialog(this,"Coroinha cadastrado com sucesso!");
            TextNome.setText("");TextIdade.setText("");TextCpf.setText("");
            TextEscala.setText("");TextTemPast.setText("");TextParoquia.setText("");
        } catch (Exception ex) { ErrosTela.mostrar(this,ex); }
    }//GEN-LAST:event_BtCadastrarActionPerformed

